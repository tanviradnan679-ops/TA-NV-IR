-- Run this in Supabase Dashboard > SQL Editor.
-- Row Level Security means each signed-in user can access only their own notes.
create table if not exists public.private_notes (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  title text not null check (char_length(title) <= 120),
  body text not null check (char_length(body) <= 10000),
  created_at timestamptz not null default now()
);

alter table public.private_notes enable row level security;

create policy "Users can read their own notes"
on public.private_notes for select
to authenticated
using ((select auth.uid()) = user_id);

create policy "Users can add their own notes"
on public.private_notes for insert
to authenticated
with check ((select auth.uid()) = user_id);

create policy "Users can delete their own notes"
on public.private_notes for delete
to authenticated
using ((select auth.uid()) = user_id);

-- No public read policy is created for private_notes.
